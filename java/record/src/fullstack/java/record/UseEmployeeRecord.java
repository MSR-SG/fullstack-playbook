package fullstack.java.record;

import java.time.LocalDate;
import java.time.Period;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;

public class UseEmployeeRecord {

    public static void main(String[] args) {
        useEmployeeRecord();
        useEmployeeRecordList();
    }

    public static void useEmployeeRecord() {
        // ---- Single record basics ----

        // Instantiate: pass every field to the constructor, in declaration order
        EmployeeRecord tom = new EmployeeRecord(6L, "Tom", LocalDate.of(1993, 8, 17), "Doha", "Designer", 40L);

        // Get: each field has an accessor method with the same name (no "get" prefix)
        System.out.println("Id: " + tom.id());
        System.out.println("Name: " + tom.name());
        System.out.println("Date of birth: " + tom.dateOfBirth());
        System.out.println("Address: " + tom.address());
        System.out.println("Designation: " + tom.designation());
        System.out.println("Department id: " + tom.departmentId());

        // Set: records are immutable, so there are no setters (tom.setAddress(...) won't compile).
        // To "change" a value, create a new record that copies the other fields.
        EmployeeRecord tomMoved = new EmployeeRecord(tom.id(), tom.name(), tom.dateOfBirth(),
                "Malta", tom.designation(), tom.departmentId());
        System.out.println("Before: " + tom);
        System.out.println("After:  " + tomMoved);
        System.out.println();
    }

    public static void useEmployeeRecordList() {
        // ---- Working with a list of records ----
        List<EmployeeRecord> employees = List.of(
                new EmployeeRecord(1L, "Eli", LocalDate.of(1990, 5, 14), "Casablanca", "Engineer", 10L),
                new EmployeeRecord(2L, "Mel", LocalDate.of(1985, 11, 2), "Singapore", "Manager", 10L),
                new EmployeeRecord(3L, "Sana", LocalDate.of(1995, 1, 23), "Jeddah", "Engineer", 20L),
                new EmployeeRecord(4L, "Leo", LocalDate.of(1988, 7, 9), "Tripoli", "Analyst", 30L),
                new EmployeeRecord(5L, "Ria", LocalDate.of(1992, 3, 30), "Phuket", "Engineer", 20L));

        // Accessors and toString are generated by the record
        EmployeeRecord first = employees.get(0);
        System.out.println("First employee: " + first);
        System.out.println("Name: " + first.name() + ", Designation: " + first.designation());

        // equals and hashCode compare all fields, not object identity
        EmployeeRecord copy = new EmployeeRecord(1L, "Eli", LocalDate.of(1990, 5, 14), "Casablanca", "Engineer", 10L);
        System.out.println("\nfirst.equals(copy): " + first.equals(copy));
        System.out.println("first == copy: " + (first == copy));
       

        // Records are immutable, so a change means creating a new record
        EmployeeRecord promoted = new EmployeeRecord(first.id(), first.name(), first.dateOfBirth(),
                first.address(), "Senior Engineer", first.departmentId());
        System.out.println("\nPromoted: " + promoted);

        // Filter
        System.out.println("\nEngineers:");
        employees.stream()
                .filter(e -> e.designation().equals("Engineer"))
                .forEach(e -> System.out.println("  " + e.name()));

        // Sort by date of birth (oldest first)
        System.out.println("\nSorted by date of birth:");
        employees.stream()
                .sorted(Comparator.comparing(EmployeeRecord::dateOfBirth))
                .forEach(e -> System.out.println("  " + e.name() + " - " + e.dateOfBirth()));

        // Group by department
        Map<Long, List<String>> namesByDepartment = employees.stream()
                .collect(Collectors.groupingBy(EmployeeRecord::departmentId,
                        Collectors.mapping(EmployeeRecord::name, Collectors.toList())));
        System.out.println("\nNames by department: " + namesByDepartment);

        // Count by designation
        Map<String, Long> countByDesignation = employees.stream()
                .collect(Collectors.groupingBy(EmployeeRecord::designation, Collectors.counting()));
        System.out.println("Count by designation: " + countByDesignation);

        // Compute ages from dateOfBirth
        LocalDate today = LocalDate.now();
        System.out.println("\nAges:");
        employees.forEach(e -> System.out.println(
                "  " + e.name() + ": " + Period.between(e.dateOfBirth(), today).getYears()));

        // Find by id
        long searchId = 3L;
        employees.stream()
                .filter(e -> e.id() == searchId)
                .findFirst()
                .ifPresentOrElse(
                        e -> System.out.println("\nFound id " + searchId + ": " + e.name()),
                        () -> System.out.println("\nNo employee with id " + searchId));
    }
}
